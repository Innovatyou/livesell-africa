#!/usr/bin/env bash
# One-time setup of a LiveSell production server: one Ubuntu 22.04/24.04 VPS (e.g. Hostinger KVM 2) running
# Postgres, Redis, the API, the web app and Nginx with HTTPS in Docker. Run as root on the new server:
#
#   curl -fsSL https://raw.githubusercontent.com/Innovatyou/livesell-africa/main/scripts/server-setup.sh -o setup.sh
#   bash setup.sh
#
# It asks for your domains, an email for the HTTPS certificate and your S3 bucket, generates every secret itself
# (nothing is printed or sent anywhere), and writes them to files only root can read. Safe to re-run: existing
# settings and certificates are kept. Releases afterwards: /srv/livesell/scripts/release.sh
set -euo pipefail

[ "$(id -u)" = 0 ] || { echo "Run as root (sudo -i)."; exit 1; }
. /etc/os-release
[ "${ID:-}" = ubuntu ] || echo "Warning: tested on Ubuntu 22.04/24.04 (this is ${PRETTY_NAME:-unknown})."

DIR=/srv/livesell
REPO=https://github.com/Innovatyou/livesell-africa.git
ask() { local v; read -rp "$1 [$2]: " v; echo "${v:-$2}"; }
secret() { openssl rand -base64 "$1" | tr -d '\n'; }
hexsecret() { openssl rand -hex "$1"; }

echo "== 1/8 System packages, firewall, swap"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq ca-certificates curl git openssl ufw certbot unattended-upgrades cron > /dev/null
if ! command -v docker > /dev/null; then curl -fsSL https://get.docker.com | sh > /dev/null; fi
systemctl enable --now docker cron > /dev/null
ufw allow OpenSSH > /dev/null && ufw allow 80/tcp > /dev/null && ufw allow 443/tcp > /dev/null && ufw --force enable > /dev/null
if ! swapon --show | grep -q .; then
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile > /dev/null && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

echo "== 2/8 Code"
if [ -d "$DIR/.git" ]; then git -C "$DIR" pull --ff-only -q; else git clone -q "$REPO" "$DIR"; fi
cd "$DIR"

echo "== 3/8 Settings"
if [ ! -f .env.deploy ]; then
  APP_DOMAIN=$(ask "Web app domain" "sell.innovative.ng")
  API_DOMAIN=$(ask "API domain" "api.$APP_DOMAIN")
  umask 077
  cat > .env.deploy <<EOF
APP_DOMAIN=$APP_DOMAIN
API_DOMAIN=$API_DOMAIN
PUBLIC_API_URL=https://$API_DOMAIN
POSTGRES_PASSWORD=$(hexsecret 24)
REDIS_PASSWORD=$(hexsecret 24)
TLS_DIR=./infra/tls
EOF
  umask 022
else
  echo "   keeping existing .env.deploy"
fi
set -a; . ./.env.deploy; set +a

if [ ! -f apps/api/.env.production ]; then
  MODE=$(ask "Environment (staging allows test payment keys; production needs live keys)" "staging")
  echo "S3 bucket for photos and documents (AWS S3 or Cloudflare R2). Input is not shown for the secret."
  S3_BUCKET=$(ask "  Bucket name" "")
  S3_REGION=$(ask "  Region (AWS e.g. eu-west-2; R2: auto)" "eu-west-2")
  S3_ENDPOINT=$(ask "  Endpoint (leave empty for AWS; R2: https://<account>.r2.cloudflarestorage.com)" "")
  S3_ACCESS_KEY_ID=$(ask "  Access key ID" "")
  read -rsp "  Secret access key: " S3_SECRET_ACCESS_KEY; echo
  [ -n "$S3_BUCKET" ] && [ -n "$S3_ACCESS_KEY_ID" ] && [ -n "$S3_SECRET_ACCESS_KEY" ] || { echo "S3 bucket and keys are required (the API refuses to start without them)."; exit 1; }
  S3_PUBLIC=$([ -n "$S3_ENDPOINT" ] && echo "" || echo "https://$S3_BUCKET.s3.$S3_REGION.amazonaws.com")
  umask 077
  cat > apps/api/.env.production <<EOF
# Generated by scripts/server-setup.sh on $(date -u +%F). Back up DATA_ENCRYPTION_KEY somewhere safe:
# losing it means sellers must re-enter their payment keys. Never commit this file.
NODE_ENV=$MODE
PORT=4000
APP_URL=https://$APP_DOMAIN
API_PUBLIC_URL=https://$API_DOMAIN
CORS_ORIGINS=https://$APP_DOMAIN
COOKIE_SECURE=true
DATABASE_URL=postgresql://livesell:$POSTGRES_PASSWORD@postgres:5432/livesell?schema=public
REDIS_URL=redis://:$REDIS_PASSWORD@redis:6379
JWT_ACCESS_SECRET=$(secret 48)
TOKEN_HASH_SECRET=$(secret 48)
DATA_ENCRYPTION_KEY=$(secret 32)
S3_REGION=$S3_REGION
S3_BUCKET=$S3_BUCKET
S3_ENDPOINT=$S3_ENDPOINT
S3_ACCESS_KEY_ID=$S3_ACCESS_KEY_ID
S3_SECRET_ACCESS_KEY=$S3_SECRET_ACCESS_KEY
S3_FORCE_PATH_STYLE=false
S3_PUBLIC_BASE_URL=$S3_PUBLIC
JOBS_ENABLED=true
PUSH_ENABLED=true
# Add later (then: docker compose ... up -d api): PAYSTACK_*, FLUTTERWAVE_*, BACHS_*, VELTRIX_*, ALERT_WEBHOOK_URL
EOF
  umask 022
  unset S3_SECRET_ACCESS_KEY
else
  echo "   keeping existing apps/api/.env.production"
fi
chmod 600 .env.deploy apps/api/.env.production

echo "== 4/8 DNS check"
IP=$(curl -fsS4 https://api.ipify.org || true)
for d in "$APP_DOMAIN" "$API_DOMAIN"; do
  got=$(getent ahostsv4 "$d" | awk 'NR==1{print $1}')
  [ "$got" = "$IP" ] && echo "   $d → $IP ok" || { echo "   $d points to '${got:-nothing}', this server is $IP. Add an A record, wait a few minutes, re-run."; exit 1; }
done

echo "== 5/8 HTTPS certificate (Let's Encrypt)"
mkdir -p infra/tls infra/nginx/acme
if [ ! -f infra/tls/fullchain.pem ]; then
  EMAIL=$(ask "Email for certificate expiry notices" "")
  docker compose --env-file .env.deploy -f docker-compose.prod.yml stop nginx > /dev/null 2>&1 || true
  # Renewal reuses these hooks: stop nginx (frees port 80), renew, copy into infra/tls, start nginx.
  certbot certonly --standalone -n --agree-tos -m "$EMAIL" -d "$APP_DOMAIN" -d "$API_DOMAIN" --cert-name livesell \
    --pre-hook "docker compose --project-directory $DIR --env-file $DIR/.env.deploy -f $DIR/docker-compose.prod.yml stop nginx" \
    --deploy-hook "cp -L /etc/letsencrypt/live/livesell/fullchain.pem /etc/letsencrypt/live/livesell/privkey.pem $DIR/infra/tls/ && chmod 600 $DIR/infra/tls/privkey.pem" \
    --post-hook "docker compose --project-directory $DIR --env-file $DIR/.env.deploy -f $DIR/docker-compose.prod.yml start nginx"
  [ -f infra/tls/fullchain.pem ] || { cp -L /etc/letsencrypt/live/livesell/fullchain.pem /etc/letsencrypt/live/livesell/privkey.pem infra/tls/; chmod 600 infra/tls/privkey.pem; }
else
  echo "   certificate already present (certbot renews it automatically)"
fi

echo "== 6/8 Build (a few minutes the first time)"
export RELEASE=$(git rev-parse --short HEAD)
DC="docker compose --env-file .env.deploy -f docker-compose.prod.yml --profile selfhosted"
DCT="$DC --profile tools"   # the one-off migrate job lives in the tools profile
$DC build && $DCT build migrate

echo "== 7/8 Database, migrations, start"
$DC up -d postgres redis
for i in $(seq 1 30); do $DC exec -T postgres pg_isready -U livesell > /dev/null 2>&1 && break; sleep 2; done
$DCT run --rm migrate
$DC up -d
for i in $(seq 1 30); do curl -fsS "https://$API_DOMAIN/health/ready" > /dev/null 2>&1 && break; sleep 3; done
curl -fsS "https://$API_DOMAIN/health/ready" > /dev/null && echo "   API healthy at https://$API_DOMAIN" || { echo "   API not healthy yet: $DC logs api --tail 50"; }

echo "== 8/8 Daily database backup (02:15, keeps 14 days)"
mkdir -p /var/backups/livesell && chmod 700 /var/backups/livesell
cat > /etc/cron.d/livesell-backup <<EOF
15 2 * * * root cd $DIR && $DC exec -T postgres pg_dump -U livesell -Fc livesell > /var/backups/livesell/livesell-\$(date +\%F).dump && find /var/backups/livesell -name '*.dump' -mtime +14 -delete
EOF

cat <<EOF

Done. LiveSell is running:
  Web:  https://$APP_DOMAIN
  API:  https://$API_DOMAIN/health/ready

Next:
  1. Register your account on the web, then make it the platform admin:
       cd $DIR && $DC exec -T postgres psql -U livesell -c "UPDATE users SET platform_role='PLATFORM_ADMIN' WHERE email='you@example.com';"
  2. Copy DATA_ENCRYPTION_KEY from apps/api/.env.production to a password manager.
  3. Payment keys: add them to apps/api/.env.production, then: $DC up -d api
  4. Copy backups off this server now and then (/var/backups/livesell).
  5. New versions: bash $DIR/scripts/release.sh
EOF
