'use client';

import { useParams } from 'next/navigation';
import { Button, ErrorState, PageLoading } from '@/components/ui';
import { useAuth } from '@/lib/auth';
import { formatMoney } from '@/lib/money';
import { ORDER_STATUS } from '@/lib/order-labels';
import type { Order, StoreProfile } from '@/lib/types';
import { useApi } from '@/lib/use-api';

/** Printable invoice (unpaid) or receipt (paid). A receipt is only shown for verified-paid orders. */
export default function PrintOrderPage() {
  const { id } = useParams<{ id: string }>();
  const { workspace } = useAuth();
  const order = useApi<Order>(`/orders/${id}`);
  const store = useApi<StoreProfile>('/store/profile');
  if (order.error) return <ErrorState message={order.error} onRetry={order.reload} />;
  if (!order.data || !store.data) return <PageLoading />;
  const o = order.data;
  const s = store.data;
  const paid = o.paymentStatus === 'PAID' || o.paymentStatus === 'PARTIALLY_REFUNDED';
  return (
    <div className="mx-auto max-w-2xl bg-surface p-8 text-sm print:max-w-none print:p-0">
      <div className="mb-6 flex justify-end gap-2 print:hidden"><Button variant="secondary" onClick={() => window.print()}>Print</Button></div>
      <div className="flex items-start justify-between gap-6">
        <div className="flex items-center gap-3">
          {s.storefront.logoUrl && <img src={s.storefront.logoUrl} alt="" className="size-14 rounded-lg object-cover" />}
          <div>
            <p className="text-lg font-semibold">{s.businessName}</p>
            <p className="text-ink-2">{[s.address, s.city, s.state].filter(Boolean).join(', ')}</p>
            <p className="text-ink-2">{s.storefront.contactPhone ?? s.phone}{s.storefront.contactEmail ? ` · ${s.storefront.contactEmail}` : ''}</p>
          </div>
        </div>
        <div className="text-right">
          <p className="text-2xl font-semibold tracking-tight">{paid ? 'Receipt' : 'Invoice'}</p>
          <p className="font-mono">{o.reference}</p>
          <p className="text-ink-2">{new Intl.DateTimeFormat('en-NG', { dateStyle: 'long' }).format(new Date(o.createdAt))}</p>
          <p className="text-ink-2">{ORDER_STATUS[o.status].label}</p>
        </div>
      </div>
      {o.customer && (
        <div className="mt-6">
          <p className="text-[12px] font-semibold uppercase tracking-wide text-ink-3">{paid ? 'Received from' : 'Bill to'}</p>
          <p className="font-medium">{o.customer.fullName}</p>
          {o.customer.phone && <p className="text-ink-2">{o.customer.phone}</p>}
          {o.shippingAddress && <p className="text-ink-2">{[o.shippingAddress.line1, o.shippingAddress.city, o.shippingAddress.state].filter(Boolean).join(', ')}</p>}
        </div>
      )}
      <table className="mt-6 w-full">
        <thead className="border-b border-ink text-left text-[12px] uppercase tracking-wide"><tr><th className="py-2">Item</th><th className="py-2 text-right">Qty</th><th className="py-2 text-right">Price</th><th className="py-2 text-right">Amount</th></tr></thead>
        <tbody className="divide-y divide-line">
          {o.items.map((i) => (
            <tr key={i.id}>
              <td className="py-2">{i.productCode ? `${i.productCode} · ` : ''}{i.productName}{i.variantName !== 'Default' ? ` (${i.variantName})` : ''}{i.discountMinor !== '0' ? ` — discount ${formatMoney(i.discountMinor, o.currency)}` : ''}</td>
              <td className="py-2 text-right tabular">{i.quantity}</td>
              <td className="py-2 text-right tabular">{formatMoney(i.unitPriceMinor, o.currency)}</td>
              <td className="py-2 text-right tabular">{formatMoney(i.lineTotalMinor, o.currency)}</td>
            </tr>
          ))}
        </tbody>
      </table>
      <dl className="ml-auto mt-4 w-64 space-y-1">
        <div className="flex justify-between"><dt>Subtotal</dt><dd className="tabular">{formatMoney(o.subtotalMinor, o.currency)}</dd></div>
        {o.discountMinor !== '0' && <div className="flex justify-between"><dt>Discount</dt><dd className="tabular">− {formatMoney(o.discountMinor, o.currency)}</dd></div>}
        <div className="flex justify-between"><dt>Delivery</dt><dd className="tabular">{formatMoney(o.deliveryFeeMinor, o.currency)}</dd></div>
        <div className="flex justify-between border-t border-ink pt-1 text-base font-semibold"><dt>{paid ? 'Paid' : 'Amount due'}</dt><dd className="tabular">{formatMoney(o.totalMinor, o.currency)}</dd></div>
      </dl>
      <p className="mt-10 text-center text-[12px] text-ink-3">livesell.africa/store/{workspace?.slug} · Generated by LiveSell Africa</p>
    </div>
  );
}
